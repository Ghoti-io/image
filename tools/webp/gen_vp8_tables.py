#!/usr/bin/env python3
"""Generate the VP8 coefficient tables from RFC 6386.

Reads the official text (third_party/rfc6386/rfc6386.txt, pinned by
tools/webp/rfc6386.sha256) and writes src/codec/webp/webp_vp8_proba.inc.
The output is committed, because a build must need neither the network nor
Python. This script is run when the pin changes, and by ``make
check-vp8-tables`` to prove that what is committed is what this script
produces from that text.

The numbers are taken from the RFC's own code blocks. Nothing here is copied
from another library. Page headers and form feeds are dropped before parsing,
because the RFC inserts them in the middle of the tables.

Usage:
    tools/webp/gen_vp8_tables.py [--rfc FILE] [--out DIR]

Copyright 2026 by Corey Pennycuff
"""

import argparse
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEFAULT_RFC = os.path.join(ROOT, "third_party", "rfc6386", "rfc6386.txt")
DEFAULT_OUT = os.path.join(ROOT, "src", "codec", "webp")
PIN = os.path.join(ROOT, "tools", "webp", "rfc6386.sha256")

# RFC 6386 section 9.6: the dequantization index is 7 bits, so section 14.1's
# dc_qlookup has 128 entries. The RFC names the bound QINDEX_RANGE and does
# not give the integer in the table's own section.
DC_QLOOKUP_LEN = 128

